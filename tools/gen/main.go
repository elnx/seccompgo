// Command gen converts the seccomp-tools Ruby syscall tables into Go source.
//
// The upstream tables are data, not code: each is a Ruby hash of name => number. This
// command parses that layout (including the x32 aliases amd64 derives) and emits
// internal/consts/tables_generated.go. Regenerating is a manual step; the build itself
// only needs the committed Go file.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"
)

type entry struct {
	name string
	num  uint32
}

var (
	entryRe = regexp.MustCompile(`^\s+([A-Za-z_][A-Za-z0-9_]*):\s*([0-9]+),?\s*$`)
	argsRe  = regexp.MustCompile(`^\s+([A-Za-z_][A-Za-z0-9_]*):\s*%w\[([^\]]*)\],?\s*$`)
)

func parseTable(path string) ([]entry, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var out []entry
	for _, line := range strings.Split(string(data), "\n") {
		m := entryRe.FindStringSubmatch(line)
		if m == nil {
			continue
		}
		n, err := strconv.ParseUint(m[2], 10, 32)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", path, err)
		}
		out = append(out, entry{m[1], uint32(n)})
	}
	if len(out) == 0 {
		return nil, fmt.Errorf("%s: no entries", path)
	}
	return out, nil
}

func parseArgs(path string) (map[string][]string, []string, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, nil, err
	}
	out := map[string][]string{}
	var order []string
	for _, line := range strings.Split(string(data), "\n") {
		m := argsRe.FindStringSubmatch(line)
		if m == nil {
			continue
		}
		var names []string
		if strings.TrimSpace(m[2]) != "" {
			names = strings.Fields(m[2])
		}
		out[m[1]] = names
		order = append(order, m[1])
	}
	if len(out) == 0 {
		return nil, nil, fmt.Errorf("%s: no entries", path)
	}
	return out, order, nil
}

func writeTables(path string, tables map[string][]entry, archOrder []string, args map[string][]string, argsOrder []string) error {
	var b bytes.Buffer
	b.WriteString("// Code generated by tools/gen; DO NOT EDIT.\n\n")
	b.WriteString("package consts\n\n")
	for _, arch := range archOrder {
		fmt.Fprintf(&b, "var %sSyscalls = []SysEntry{\n", arch)
		for _, e := range tables[arch] {
			fmt.Fprintf(&b, "\t{%q, %d},\n", e.name, e.num)
		}
		b.WriteString("}\n\n")
	}
	b.WriteString("// SyscallTables holds each architecture's syscall table in source order.\n")
	b.WriteString("var SyscallTables = map[string][]SysEntry{\n")
	for _, arch := range archOrder {
		fmt.Fprintf(&b, "\t%q: %sSyscalls,\n", arch, arch)
	}
	b.WriteString("}\n\n")
	b.WriteString("// SyscallTableOrder is the order the upstream code enumerates architectures in.\n")
	b.WriteString("var SyscallTableOrder = []string{")
	for i, arch := range archOrder {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(&b, "%q", arch)
	}
	b.WriteString("}\n\n")
	b.WriteString("// SyscallArgs maps a syscall name to its argument names.\n")
	b.WriteString("var SyscallArgs = map[string][]string{\n")
	for _, name := range argsOrder {
		vals := args[name]
		fmt.Fprintf(&b, "\t%q: {", name)
		for i, v := range vals {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "%q", v)
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		return fmt.Errorf("gofmt: %w\n%s", err, b.String())
	}
	return os.WriteFile(path, src, 0o644)
}

func main() {
	src := flag.String("src", "../seccomp-tools/lib/seccomp-tools/consts", "path to the Ruby consts directory")
	out := flag.String("out", "internal/consts/tables_generated.go", "output Go file")
	flag.Parse()

	archs := []string{"aarch64", "amd64", "i386", "riscv64", "s390x"}
	tables := map[string][]entry{}
	for _, arch := range archs {
		es, err := parseTable(filepath.Join(*src, "sys_nr", arch+".rb"))
		if err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		if arch == "amd64" {
			// The upstream table appends an x32_ alias for every native syscall:
			// h[:"x32_#{k}"] = h[k] | X32_MODE_BIT. Aliases come after the native entries.
			base := append([]entry(nil), es...)
			for _, e := range base {
				es = append(es, entry{"x32_" + e.name, e.num | 0x40000000})
			}
		}
		tables[arch] = es
	}
	args, argsOrder, err := parseArgs(filepath.Join(*src, "sys_arg.rb"))
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	// The ABI order used by the scanner is the Ruby ABI hash order, not alphabetical.
	abiOrder := []string{"amd64", "i386", "aarch64", "riscv64", "s390x"}
	if err := writeTables(*out, tables, abiOrder, args, argsOrder); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Printf("wrote %s (%d syscalls, %d prototypes)\n", *out, countTables(tables), len(args))
}

func countTables(t map[string][]entry) int {
	n := 0
	for _, v := range t {
		n += len(v)
	}
	return n
}
